import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const release=JSON.parse(fs.readFileSync('release/update.json','utf8'));
const apk=fs.readFileSync('release/psql-mobile.apk');
assert.equal(crypto.createHash('sha256').update(apk).digest('hex'),release.sha256,'Release APK hash');
assert.equal(apk.length,release.size,'Release APK size');
assert.equal(release.apkUrl,'https://danielperrella.github.io/psql-mobile/psql-mobile.apk');
const gradle=fs.readFileSync('android/app/build.gradle','utf8');
assert.equal(Number(gradle.match(/def publishedVersionCode = (\d+)/)[1]),release.versionCode,'Published Android version');
assert.equal(gradle.match(/versionName '([^']+)'/)[1],release.versionName);
assert.equal(fs.readFileSync('src/main.js','utf8').match(/const version='([^']+)'/)[1],release.versionName);
const sdk=process.env.ANDROID_HOME||process.env.ANDROID_SDK_ROOT||(fs.existsSync('android/local.properties')?fs.readFileSync('android/local.properties','utf8').match(/^sdk.dir=(.+)$/m)?.[1].trim():null);
assert.ok(sdk,'Android SDK is required to verify APK metadata');
const aapt=path.join(sdk,'build-tools','35.0.0',process.platform==='win32'?'aapt.exe':'aapt');
const metadata=execFileSync(aapt,['dump','badging','release/psql-mobile.apk'],{encoding:'utf8'});
const identity=metadata.match(/package: name='([^']+)' versionCode='(\d+)' versionName='([^']+)'/);
assert.ok(identity,'APK package metadata');assert.equal(identity[1],'it.psqlmobile.app');
assert.equal(Number(identity[2]),release.versionCode);assert.equal(identity[3],release.versionName);
console.log(`Verified signed release payload ${release.versionName} (${release.versionCode}).`);
